"""Bake the welcome screen's dotted globe: the land points of a regular grid, from Natural Earth.

The globe (frontend/src/components/Globe.tsx) draws one dot wherever there is land, so visitors
download only these points, never a map. The land comes from the world-atlas package (Natural
Earth's public-domain 1:50m land, as TopoJSON):

    npm pack world-atlas@2.0.2   # then unpack package/land-50m.json somewhere

Usage (from the repo root):
    python -m scripts.make_globe_dots path/to/land-50m.json
"""

import json
import math
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "frontend" / "src" / "globeDots.ts"
STEP_DEG = 2.4  # between neighbouring dots, along a meridian and (on the ground) along a parallel
LAT_RANGE = (-56.0, 82.0)  # Antarctica is left out: the tilted globe hardly shows it


def rings(topology: dict) -> list[list[tuple[float, float]]]:
    """Every ring of the land MultiPolygon as (lng, lat) points, decoded from the quantized arcs."""
    (sx, sy), (tx, ty) = topology["transform"]["scale"], topology["transform"]["translate"]
    arcs = []
    for arc in topology["arcs"]:
        x = y = 0
        points = []
        for dx, dy in arc:  # delta-encoded
            x, y = x + dx, y + dy
            points.append((x * sx + tx, y * sy + ty))
        arcs.append(points)
    result = []
    for geometry in topology["objects"]["land"]["geometries"]:
        polygons = geometry["arcs"] if geometry["type"] == "MultiPolygon" else [geometry["arcs"]]
        for polygon in polygons:
            for ring in polygon:
                points: list[tuple[float, float]] = []
                for index in ring:
                    arc = arcs[index] if index >= 0 else arcs[~index][::-1]
                    points.extend(arc if not points else arc[1:])
                result.append(points)
    return result


def is_land(lng: float, lat: float, indexed: list[tuple[tuple[float, float, float, float], list]]) -> bool:
    """Even-odd rule over all rings (holes such as the Caspian count as water)."""
    inside = False
    for (x0, y0, x1, y1), ring in indexed:
        if not (x0 <= lng <= x1 and y0 <= lat <= y1):
            continue
        for (xi, yi), (xj, yj) in zip(ring, ring[-1:] + ring[:-1], strict=True):
            if (yi > lat) != (yj > lat) and lng < (xj - xi) * (lat - yi) / (yj - yi) + xi:
                inside = not inside
    return inside


def main() -> None:
    topology = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    indexed = []
    for ring in rings(topology):
        xs, ys = [p[0] for p in ring], [p[1] for p in ring]
        indexed.append(((min(xs), min(ys), max(xs), max(ys)), ring))
    dots = []
    lat = LAT_RANGE[0]
    while lat <= LAT_RANGE[1]:
        lng_step = STEP_DEG / max(0.2, math.cos(math.radians(lat)))
        lng = -180.0
        while lng < 180.0:
            if is_land(lng, lat, indexed):
                dots += [round(lat * 10), round(lng * 10)]
            lng += lng_step
        lat += STEP_DEG
    rows = [", ".join(map(str, dots[i : i + 24])) for i in range(0, len(dots), 24)]
    OUT.write_text(
        "// Land dots of the welcome screen's globe: latitude, longitude pairs in tenths of a degree.\n"
        "// Generated by scripts/make_globe_dots.py from Natural Earth (public domain): don't edit.\n"
        "export const GLOBE_DOTS = [\n" + "".join(f"  {row},\n" for row in rows) + "];\n",
        encoding="utf-8",
    )
    print(f"{len(dots) // 2} dots -> {OUT}")


if __name__ == "__main__":
    main()
